function test_radial_slotted_repair_characterization()
%TEST_RADIAL_SLOTTED_REPAIR_CHARACTERIZATION Target active repair branches.
base=[.32;.8;.2;.1;.5;.002;.1;2;.8;.7;.6;.4;.05;5.2;.025;.7];
cases={ ...
 'minimum tm',7,0.001; 'minimum tbi',8,0.001; 'minimum ty',2,0.001; ...
 'origin clearance',1,0.03; 'maximum shoe base',4,1; ...
 'maximum tc',3,1.5; 'minimum tc',3,0.001; 'shoe removal',5,0; ...
 'minimum gap',6,1e-6; 'slot side angle',10,0.99; ...
 'slot base angle',11,0.001; 'yoke overlap',11,1.2; ...
 'shoe overlap',10,1.2; 'opening enlarge',12,0.001; ...
 'opening cap',10,0.001; 'minimum strand',15,1e-8; ...
 'branch low',16,0; 'branch high',16,1};
for orientation={'external','internal'}
    for k=1:size(cases,1)
        chrom=base; chrom(cases{k,2})=cases{k,3};
        rnfoundry.em.test.assertCandidateLegacyParity(chrom, ...
            struct('ArmatureType',orientation{1}),struct());
    end
end
% Maximum-strand/NStrands repair, and representative branch boundaries.
for branch=[0.1,0.49,0.51,0.9]
    chrom=base; chrom(16)=branch;
    sim=struct('MaxStrandDiameter',0.6e-3);
    rnfoundry.em.test.assertCandidateLegacyParity(chrom, ...
        struct('ArmatureType','internal'),sim);
end
end
