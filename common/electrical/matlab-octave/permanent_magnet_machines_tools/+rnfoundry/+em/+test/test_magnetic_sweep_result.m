function test_magnetic_sweep_result()
n=3;
s=struct('Positions',(0:n-1).','CoggingTorque',zeros(n,1), ...
 'DirectFluxLinkage',zeros(n,3),'ToothFluxDensity',ones(n,1), ...
 'SlotVectorPotential',struct('Position',zeros(n,2),'Integral',zeros(n,2)), ...
 'SlotFlux',struct('Position',zeros(n,2),'Integral',zeros(n,2)), ...
 'AirGapField',struct('Theta',[0,1],'Magnitude',zeros(n,2)), ...
 'CoilArea',1,'ArmatureIronArea',2,'PerPoleRadialForce',3, ...
 'Provenance',struct('Solver','xfemm.femmsession'));
r=rnfoundry.em.fea.MagneticSweepResult(s);
assert(r.CoilArea==1 && r.PerPoleRadialForce==3);
s.CoggingTorque=zeros(2,1);
rnfoundry.em.test.assertError(@() rnfoundry.em.fea.MagneticSweepResult(s), ...
    'rnfoundry:em:InvalidMagneticSweepResult');
end
